-- V10：给"自动复制"留下**源行 id**（04-081）。
--
-- 背景：复用同源草稿时要重建"源行 → 草稿行"的映射，而原先只能按**业务键**配对（维度 `(sort_no, name)`、
-- 指标 `code`）。但业务键是**可编辑字段**：用户在草稿里改个名，复用时就配不上（只能报 2015）；
-- 同序号同名还会配对塌陷（03 §31.7.14 的 P2-11）。记下源行 id 之后，**身份与业务键解耦**。
--
-- 落地口径：
--   · 两列都**可空**，**不动既有数据**（老草稿为 NULL ⇒ 服务层回退到业务键配对，行为与今天一致）；
--   · **不回填历史行**：源行与草稿行的对应关系在历史数据里没有可靠依据（那正是要解决的问题），
--     硬猜一个 id 比留 NULL 更糟 —— NULL 至少让回退路径走明确的老逻辑；
--   · **编号**：本脚本吃 `V10` ⇒ 13 §E1 顺延（评估五表 `V11`、通知 `V12`、P4 的 `V13`）；
--   · **权限**：只用 `ALTER`（应用账号有 `ALTER ON spe.*`），不涉及任何越界权限（04-077/04-078）。

ALTER TABLE dimension
  ADD COLUMN src_dimension_id BIGINT NULL COMMENT '复制来源行 id：本行由自动复制产生时，记下源版本里对应的 dimension.id（04-081；NULL = 老数据，服务层回退按业务键配对）';

ALTER TABLE indicator
  ADD COLUMN src_indicator_id BIGINT NULL COMMENT '复制来源行 id：同上，指向源版本里对应的 indicator.id（04-081）';
